package fourSome.model;

public class SocketTypes {
    private int socketId;
    private String socketName;
    private String status;

    public SocketTypes() {}

    public int getSocketId() { return socketId; }
    public void setSocketId(int socketId) { this.socketId = socketId; }
    public String getSocketName() { return socketName; }
    public void setSocketName(String socketName) { this.socketName = socketName; }
    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }
}